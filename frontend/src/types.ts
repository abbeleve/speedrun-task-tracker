// One representative emoji per category, in EMOJI_CATEGORIES order — used for
// the picker's quick-jump tab strip.
export const EMOJI_CATEGORY_ICONS: Record<string, string> = {};
for (const entry of EMOJI_DATA) {
  if (!(entry.category in EMOJI_CATEGORY_ICONS)) EMOJI_CATEGORY_ICONS[entry.category] = entry.emoji;
}

export interface EmojiGroup {
  category: string;
  emojis: string[];
}

// Splits the (optionally keyword-filtered) emoji list into EMOJI_CATEGORIES-ordered
// groups, dropping empty ones — the shape the picker renders sections from.
export function groupedEmojis(query: string): EmojiGroup[] {
  const q = query.trim().toLowerCase();
  const filtered = q
    ? EMOJI_DATA.filter((e) => e.keywords.some((k) => k.includes(q)) || e.emoji === q)
    : EMOJI_DATA;
  const byCategory = new Map<string, string[]>();
  for (const e of filtered) {
    const list = byCategory.get(e.category);
    if (list) list.push(e.emoji);
    else byCategory.set(e.category, [e.emoji]);
  }
  const groups: EmojiGroup[] = [];
  for (const cat of EMOJI_CATEGORIES) {
    const emojis = byCategory.get(cat);
    if (emojis && emojis.length > 0) groups.push({ category: cat, emojis });
  }
  return groups;
}